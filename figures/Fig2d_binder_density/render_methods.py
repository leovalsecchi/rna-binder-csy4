#!/usr/bin/env python
"""
render_methods.py
=================

One rendering per backbone design method: the csy4 target in neutral grey with
that method's binder-density map over it, in that method's stack colour.

Follows LV_ThesisFigures/code/common/CHIMERAX_RENDERING.md:
  * colours by NAME from config/thesis_colors.cxc, never a hand-picked hex
  * RNA neutral (thesis_grey_300), silhouettes thesis_grey_700 width 1.5
  * `set bgColor white` even with transparentBackground, or the PNG composites
    to black wherever a viewer ignores alpha
  * supersample 3; width 1800 screen / 3000 print
  * no `;` lines in a .cxc - they parse as a command and abort the rest
  * `nucleotides` only acts on DISPLAYED atoms, and bases need `target a` too

The camera is fitted to the TARGET only (`view #1`), never to everything: each
method's map has its own bounding box (390k voxels for BoltzGen, 1,023k for
HalluDesign), so fitting to the scene would silently draw the four panels at
four different scales and make the comparison meaningless.

The two surface levels are fixed and identical in all four panels, which is the
only way the colour means the same thing in each: an outer shell at --outer and
a solid core at --inner, both as "% of that method's binders reaching here".
Both sit below the lowest per-method peak (BoltzDesign, 63.1%), so every panel
shows both shells.

    python render_methods.py --maps maps --out renders          # write .cxc
    python render_methods.py --maps maps --out renders --render  # and run ChimeraX
"""

import argparse
import csv
import os
import subprocess
import sys
import time

CHIMERAX = "/Applications/ChimeraX-1.11.1.app"
BIN = CHIMERAX + "/Contents/MacOS/ChimeraX"

# group -> the colour NAME defined in thesis_colors.cxc
COLOUR_NAME = {
    "RFD3": "thesis_rfd3_limpnn",
    "BoltzGen": "thesis_bg_limpnn",
    "BoltzDesign": "thesis_boltzdesign_limpnn",
    "HalluDesign": "thesis_hallu_limpnn",
}

TEMPLATE = """\
# {group} - binder density on csy4, {n} design backbones
# generated by render_methods.py, do not hand-edit
open thesis_colors.cxc
open {target}
open {map} id #2

set bgColor white
graphics silhouettes true width 1.5 color thesis_grey_700
light soft

# target: neutral grey, house tube/slab nucleotides.
# `show atoms` must come first or `nucleotides` silently does nothing.
# The colour command carries NO target: a slab takes the whole-residue colour,
# and `target ac` leaves the bases in ChimeraX's default per-base rainbow.
hide atoms
cartoon
show #1 atoms
nucleotides #1 tube/slab
color #1 thesis_grey_300

# the density: one level, identical in every panel, so the colour means the
# same thing in each. {level}% = reached by that share of the method's binders.
volume #2 style surface level {level} color {colour} transparency {transp} step 1
volume #2 showOutlineBox false
{envelope}

{canonical}
# camera from the TARGET alone, so all four panels share one scale
view #1
zoom {zoom}
{orient}
save {png} width {width} supersample 3 transparentBackground true
"""


def write_cxc(path, **kw):
    with open(path, "w") as fh:
        fh.write(TEMPLATE.format(**kw))


def render(cxc_dir, names, pngs, timeout=420):
    """Run ChimeraX once per scene, ONE AT A TIME.

    `open -g` launches behind the front window instead of stealing focus, and
    --nogui is NOT usable: it runs the script but saves no image (no OpenGL).

    Sequential on purpose. `open -a` against an already-running app activates
    the existing instance instead of starting a second one, and the --args are
    then dropped, so firing all four at once renders the first scene four times
    or nothing at all. Each PNG is deleted before its own launch, so the wait
    cannot be satisfied by a stale file from an earlier run.
    """
    ok = True
    for name, png in zip(names, pngs):
        if os.path.exists(png):
            os.unlink(png)
        subprocess.run(["open", "-g", "-a", CHIMERAX, "--args", "--exit",
                        "--cmd", "cd %s; open %s" % (cxc_dir, name)], check=True)
        start = time.time()
        while time.time() - start < timeout:
            if os.path.exists(png) and os.path.getsize(png) > 0:
                time.sleep(2)                   # let the write finish
                break
            time.sleep(3)
        else:
            print("timed out waiting for %s" % png)
            ok = False
    return ok


def validate(cxc_dir, name):
    """Surface command errors without rendering: --nogui parses and runs
    everything, and only the `save` fails."""
    p = subprocess.run([BIN, "--nogui", "--exit", "--silent",
                        "--cmd", "cd %s; open %s" % (cxc_dir, name)],
                       capture_output=True, text=True, timeout=300)
    bad = [ln for ln in (p.stdout + p.stderr).splitlines()
           if "rror" in ln and "OpenGL" not in ln and "offscreen" not in ln.lower()
           and "Unable to save image" not in ln]
    return bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--maps", default="maps")
    ap.add_argument("--out", default="renders")
    ap.add_argument("--level", type=float, default=50.0,
                    help="surface level, %% of that method's binders reaching "
                         "a point. 50%% encloses 236-1539 A^3 depending on "
                         "method; 20%% encloses 5433-8884, which is the size "
                         "of the RNA itself and hides it.")
    ap.add_argument("--envelope", type=float, default=None,
                    help="optional second, fainter level drawn as mesh")
    # At level 30 the shell sits in front of the hairpin in the house view.
    # 0.2 hides the RNA, 0.75 washes the stack colour out, and mesh at a 1 A
    # grid is an unreadable black wireframe. 0.55 shows both.
    ap.add_argument("--transparency", type=float, default=0.55)
    # Every structure panel in the book starts from one saved csy4 orientation,
    # applied BEFORE `view`: Fig5b 0.391719,-0.856212,0.336834 127.9238;
    # Fig5c and Fig5c_surface 0.382530,-0.870162,0.310626 127.6603; Fig5d
    # 0.385502,-0.861134,0.331415 132.5178. Those are nearly the same axis, so
    # Fig5c's is taken as the house view here. It is defined in the frame of
    # that panel's reference file, so this target has to be matched onto it
    # first (16 nt, RMSD 1.18 A - the real free-vs-bound hairpin difference).
    ap.add_argument("--canonical-ref", default=None,
                    help="reference .pdb whose frame the house orientation is "
                         "defined in; omit to render in the map's own frame")
    ap.add_argument("--canonical-turn",
                    default="0.382530,-0.870162,0.310626 127.6603")
    ap.add_argument("--ref-chain", default="#9.2/B",
                    help="the RNA of the reference; it carries 3 submodels")
    # Raw commands placed BEFORE `view`, ';' separated. This is where a computed
    # model transform goes - e.g. standing the hairpin on its helical axis
    # (maps/upright.txt) and leaning it toward the viewer. It must precede
    # `view`, or the object rotates out of frame instead of being reframed.
    ap.add_argument("--pre-view", default=None)
    ap.add_argument("--zoom", type=float, default=0.85)
    ap.add_argument("--width", type=int, default=3000, help="3000 print, 1800 screen")
    ap.add_argument("--orient", default="turn y 120; turn z -90",
                    help="fixed orientation, applied identically to all four; "
                         "several commands separated by ';' (a .cxc cannot "
                         "carry ';' itself, so they are written one per line). "
                         "The default is the approved front view, rolled so the "
                         "hairpin's truncated ends sit at the bottom.")
    ap.add_argument("--render", action="store_true")
    ap.add_argument("--no-validate", action="store_true")
    args = ap.parse_args()

    maps = os.path.abspath(args.maps)
    out = os.path.abspath(args.out)
    os.makedirs(out, exist_ok=True)
    for f in ("thesis_colors.cxc", "1_csy4_target.pdb"):
        src = os.path.join(maps, f)
        if not os.path.exists(src):
            ap.error("missing %s" % src)

    rows = list(csv.DictReader(open(os.path.join(maps, "legend.csv"))))
    names, pngs = [], []
    for r in rows:
        group = r["group"]
        if group not in COLOUR_NAME:
            print("no colour name for %r - skipped" % group)
            continue
        png = os.path.join(out, "density_%s.png" % group)
        cxc = "render_%s.cxc" % group
        env = ""
        if args.envelope is not None:
            env = ("open %s id #3\n"
                   "volume #3 style mesh level %g color %s transparency 0.75 step 1\n"
                   "volume #3 showOutlineBox false"
                   % (r["expected_map"], args.envelope, COLOUR_NAME[group]))
        canonical = ""
        if args.pre_view:
            canonical = "\n".join(c.strip() for c in args.pre_view.split(";")
                                  if c.strip())
        if args.canonical_ref:
            # `bring` is why this is matchmaker and not align: align moves
            # atomic models only and would leave the map behind, in the old
            # frame, still looking plausible.
            canonical = (
                "# into the book's shared csy4 frame, then the house orientation\n"
                "open %s id #9\n"
                "matchmaker #1/A to %s bring #2\n"
                "close #9\n"
                "turn %s center 0,0,0 models #1-2"
                % (args.canonical_ref, args.ref_chain, args.canonical_turn))
        write_cxc(os.path.join(maps, cxc), group=group, n=r["n_binders"],
                  target="1_csy4_target.pdb", map=r["expected_map"],
                  colour=COLOUR_NAME[group], level=args.level, envelope=env,
                  zoom=args.zoom,
                  orient="\n".join(c.strip() for c in args.orient.split(";")
                                   if c.strip()),
                  png=png, width=args.width,
                  canonical=canonical, transp=args.transparency)
        names.append(cxc)
        pngs.append(png)
        print("%-12s %-26s %s  level %g%%%s"
              % (group, COLOUR_NAME[group], r["expected_map"], args.level,
                 "" if args.envelope is None else " + %g%% mesh" % args.envelope))

    if not args.no_validate:
        bad = validate(maps, names[0])
        if bad:
            print("\ncommand errors in %s - not rendering:" % names[0])
            for ln in bad[:12]:
                print("   ", ln)
            return 1
        print("validated %s with no command errors" % names[0])

    if not args.render:
        print("wrote %d .cxc to %s (pass --render to run ChimeraX)"
              % (len(names), maps))
        return 0

    ok = render(maps, names, pngs)
    for p in pngs:
        print("%-9s %s" % ("ok" if os.path.exists(p) else "MISSING",
                           p + ("  %d KB" % (os.path.getsize(p) // 1024)
                                if os.path.exists(p) else "")))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
